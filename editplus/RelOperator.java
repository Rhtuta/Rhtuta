class RelOperator 
{
	public static void main(String[] args) 
	{
		int a = 20, b = 15;
		
		System.out.println("a==b -> "+(a==b));
		System.out.println("a!=b -> "+(a!=b));
		System.out.println("a<b ->  "+(a<b));
		System.out.println("a>b ->  "+(a>b));
		System.out.println("a<=b -> "+(a<=b));
		System.out.println("a>=b -> "+(a>=b));
		
		
	}
}
